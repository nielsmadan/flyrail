// Command gen writes the Unicode full case folding table (statuses C and F) from a CaseFolding.txt snapshot.
package main

import (
	"bytes"
	"errors"
	"flag"
	"fmt"
	"go/format"
	"os"
	"regexp"
	"slices"
	"strconv"
	"strings"
)

var versionHeader = regexp.MustCompile(`^# CaseFolding-([0-9.]+)\.txt$`)

type mapping struct {
	code   rune
	folded []rune
}

func parse(source string) (string, []mapping, error) {
	lines := strings.Split(source, "\n")
	match := versionHeader.FindStringSubmatch(strings.TrimRight(lines[0], "\r"))
	if match == nil {
		return "", nil, errors.New("CaseFolding.txt has an unrecognized version header")
	}
	var result []mapping
	for _, line := range lines {
		body, _, _ := strings.Cut(line, "#")
		body = strings.TrimSpace(body)
		if body == "" {
			continue
		}
		fields := strings.Split(body, ";")
		if len(fields) < 3 {
			return "", nil, fmt.Errorf("malformed line %q", line)
		}
		status := strings.TrimSpace(fields[1])
		if status != "C" && status != "F" {
			continue
		}
		code, err := parseRune(strings.TrimSpace(fields[0]))
		if err != nil {
			return "", nil, err
		}
		var folded []rune
		for _, item := range strings.Fields(fields[2]) {
			value, err := parseRune(item)
			if err != nil {
				return "", nil, err
			}
			folded = append(folded, value)
		}
		result = append(result, mapping{code: code, folded: folded})
	}
	slices.SortFunc(result, func(a, b mapping) int { return int(a.code - b.code) })
	return match[1], result, nil
}

func parseRune(text string) (rune, error) {
	var value rune
	if _, err := fmt.Sscanf(text, "%x", &value); err != nil {
		return 0, fmt.Errorf("malformed code point %q: %w", text, err)
	}
	return value, nil
}

func render(version string, mappings []mapping) ([]byte, error) {
	var out bytes.Buffer
	out.WriteString("// Code generated by internal/unicodex/gen from testdata/CaseFolding-" + version + ".txt; DO NOT EDIT.\n\n")
	out.WriteString("package unicodex\n\n")
	out.WriteString("// CaseFoldingVersion is the Unicode version of the full case folding table.\n")
	out.WriteString("const CaseFoldingVersion = \"" + version + "\"\n\n")
	out.WriteString("var foldTable = [...]foldEntry{\n")
	for _, entry := range mappings {
		fmt.Fprintf(&out, "\t{0x%04X, %s},\n", entry.code, strconv.QuoteToASCII(string(entry.folded)))
	}
	out.WriteString("}\n")
	return format.Source(out.Bytes())
}

func run(source, output string, check bool) error {
	data, err := os.ReadFile(source)
	if err != nil {
		return err
	}
	version, mappings, err := parse(string(data))
	if err != nil {
		return err
	}
	rendered, err := render(version, mappings)
	if err != nil {
		return err
	}
	if !check {
		return os.WriteFile(output, rendered, 0o600)
	}
	current, err := os.ReadFile(output)
	if err != nil {
		return err
	}
	if !bytes.Equal(current, rendered) {
		return fmt.Errorf("%s is stale; run go generate ./internal/unicodex", output)
	}
	return nil
}

func main() {
	check := flag.Bool("check", false, "fail when the output differs instead of writing it")
	flag.Parse()
	if flag.NArg() != 2 {
		fmt.Fprintln(os.Stderr, "usage: gen [-check] CaseFolding.txt output.go")
		os.Exit(2)
	}
	if err := run(flag.Arg(0), flag.Arg(1), *check); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
