"""Write or check internal/sysx/errnotext_<os>.go from this platform's os.strerror (libc wording)."""

import argparse
import json
import os
import sys
from pathlib import Path

PROBE = 1_000_000
LIMIT = 4096


def unknown_prefix() -> str:
    text = os.strerror(PROBE)
    if not text.endswith(str(PROBE)):
        raise ValueError(f"unexpected unknown-errno text: {text!r}")
    return text[: -len(str(PROBE))]


def render(platform: str) -> str:
    prefix = unknown_prefix()
    known = [code for code in range(1, LIMIT) if not os.strerror(code).startswith(prefix)]
    rows = "\n".join(f"\t{json.dumps(os.strerror(code))}," for code in range(max(known) + 1))
    return f"""// Code generated by scripts/generate_errno_text.py from {platform} os.strerror; DO NOT EDIT.

package sysx

const unknownErrnoPrefix = {json.dumps(prefix)}

var errnoText = [...]string{{
{rows}
}}
"""


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail when the committed table is stale")
    arguments = parser.parse_args()
    if sys.platform not in {"darwin", "linux"}:
        print(f"errno tables are generated on darwin and linux, not {sys.platform}", file=sys.stderr)
        return 1
    output = Path(__file__).resolve().parents[1] / f"internal/sysx/errnotext_{sys.platform}.go"
    rendered = render(sys.platform)
    if not arguments.check:
        output.write_text(rendered, encoding="utf-8")
        return 0
    if output.read_text(encoding="utf-8") != rendered:
        print(f"{output.name} differs from this platform's os.strerror; run go generate ./internal/sysx", file=sys.stderr)
        return 1
    print(f"{output.name} matches {sys.platform} os.strerror")
    return 0


if __name__ == "__main__":
    sys.exit(main())
